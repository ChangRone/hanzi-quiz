import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
const require = createRequire(import.meta.url);
const { normalizeEvent, countsForMastery } = require('../../assets/review-event-v2.js');
const legacy = { id:'historical-1', appVersion:'old', char:'貓', skill:'context_write', skillKey:'貓|context_write', courseKey:'20262020|03', reviewedAt:'2026-10-01T00:00:00.000Z', result:'pass', mode:'normal', allowBackwards:true };
const before = JSON.stringify(legacy);
const migrated = normalizeEvent(legacy);
assert.equal(JSON.stringify(legacy), before, 'original is unchanged');
assert.deepEqual(migrated, { ...legacy, eventType:'tested' }, 'all legacy fields preserved');
assert.equal(countsForMastery(migrated), true);
assert.equal(countsForMastery({ ...migrated, eventType:'exposed', result:null }), false);
assert.equal(normalizeEvent(migrated).id, legacy.id, 'idempotent');
assert.throws(() => normalizeEvent({ id:'ambiguous' }), /cannot be classified safely/);
assert.throws(() => normalizeEvent({ id:'bad', result:'pass', eventType:'future' }), /Unknown/);
const app = readFileSync(new URL('../../assets/app.js', import.meta.url), 'utf8');
assert.match(app, /const DB_VERSION = 2;/);
assert.match(app, /\.openCursor\(\)/);
assert.match(app, /countsForMastery\(event\)/);
assert.match(app, /eventType: 'exposed'/);
assert.match(app, /eventType: 'tested'/);
console.log('REVIEW_EVENT_V2_MIGRATION_SMOKE=PASS');
